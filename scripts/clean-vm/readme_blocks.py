"""readme_blocks.py <README.md> <vm> <out.sh> [--no-substitute]

Builds one VM's install script from README.md's fenced blocks, found by
their exact heading line, never by line number. Every README line is
copied byte for byte except these substitutions, each printed as a
`# SUBSTITUTED` line:
  pre-tag (the default): each `curl ... -o "$workdir/X"` line of the
           package block becomes `cp ~/cand/"X" "$workdir/"`, since the
           release does not exist yet (sha256sum -c still runs);
  the README's own "# Ubuntu X.Y: this line instead of the one above."
           swap, on the VM whose release is X.Y.
With --no-substitute (after the tag) only that README swap remains.
Steps the README gives in prose (the cargo route to zellij, the tmux
config file and its chmod, the waybar config file and its enable) come
from the README's own inline code under a `# ---- PROSE` heading; lines
the harness adds (set -e, mkdir, the file writes, the install and
--version probes) follow a `# HARNESS` line. The script runs under
`set -e`, so its exit status is the first failure, not the last line's.
"""
import pathlib
import re
import sys

# Run with -I, which leaves the script's own directory off sys.path.
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from vms import vm as lookup  # noqa: E402

FEDORA = "### Fedora 44 and 45: the RPM"
UBUNTU = "### Ubuntu 26.04 and 26.10: river from a PPA, then the .deb"
# The `# ---- … ----` labels written into a script keep the section names
# rc.3's run recorded ("Requirements", "Running it"), so a heading rename
# leaves every generated script byte-identical; only these lookups follow.
MULTIPLEXER = "### Session multiplexer"
STATUS_BAR = "## Status bar"
TRUST = "### When something in the file is wrong"
PACKAGED_SESSION = "### The packaged session"
HEREDOC = "BUOY_README_BLOCK"
INSTEAD = re.compile(r"^# Ubuntu ([0-9]+\.[0-9]+): this line instead of the one above\.$")


class Readme:
    """README.md's sections and fenced blocks, located by exact heading line."""

    def __init__(self, text: str) -> None:
        self.lines = text.splitlines()

    def section(self, heading: str) -> list[str]:
        """The lines under the exact heading line, up to the next heading
        outside a fence (a `# comment` inside a block is not one)."""
        try:
            start = self.lines.index(heading) + 1
        except ValueError:
            raise SystemExit(f"README.md: no heading line {heading!r}") from None
        body, fence = [], False
        for line in self.lines[start:]:
            if line.startswith("```"):
                fence = not fence
            elif not fence and re.match(r"#+ ", line):
                break
            body.append(line)
        return body

    def blocks(self, heading: str, lang: str, count: int) -> list[str]:
        """Exactly count ```lang blocks under the heading, each as text ending in a newline."""
        found, current = [], None
        for line in self.section(heading):
            if current is None and line == f"```{lang}":
                current = []
            elif current is not None and line == "```":
                found.append("".join(f"{l}\n" for l in current))
                current = None
            elif current is not None:
                current.append(line)
        if len(found) != count:
            raise SystemExit(f"README.md: {len(found)} ```{lang} blocks under {heading!r}, expected {count}")
        return found

    def code_span(self, heading: str, pattern: str) -> str:
        """The first inline `code` under the heading matching pattern, whitespace folded."""
        m = re.search(rf"`({pattern})`", "\n".join(self.section(heading)))
        if not m:
            raise SystemExit(f"README.md: no `{pattern}` under {heading!r}")
        return " ".join(m.group(1).split())


class Script:
    """The generated script, and the log of what was not copied verbatim."""

    def __init__(self, vm: str) -> None:
        self.parts = ["#!/usr/bin/bash", f"# README.md install for {vm}; generated by readme_blocks.py",
                      "# HARNESS", "set -e", "cd ~"]
        self.log: list[str] = []

    def add(self, *lines: str) -> None:
        """Append lines (a block's text counts as one entry)."""
        self.parts.extend(lines)

    def swap(self, block: str, old: str, new: str, why: str) -> str:
        """Replace exactly one occurrence, logged; anything else is an error."""
        n = block.count(old)
        if n != 1:
            raise SystemExit(f"substitution needle found {n}x ({why}): {old!r}")
        self.log.append(f"# SUBSTITUTED ({why}): {old.strip()!r} -> {new.strip()!r}")
        return block.replace(old, new)

    def heredoc(self, path: str, body: str) -> str:
        """`cat > path` of body, refusing a body that contains the delimiter line."""
        if f"\n{HEREDOC}\n" in f"\n{body}":
            raise SystemExit(f"README.md: a block written to {path} contains the line {HEREDOC}")
        return f"cat > {path} <<'{HEREDOC}'\n{body}{HEREDOC}"


def pre_tag(script: Script, block: str) -> str:
    """The package block with each download turned into a copy of the candidate."""
    downloads = [line for line in block.splitlines(keepends=True) if line.startswith("curl ")]
    if len(downloads) != 2:
        raise SystemExit(f"README.md: {len(downloads)} curl lines in a package block, expected 2 (package, .sha256)")
    for line in downloads:
        m = re.search(r'-o "\$workdir/([^"]+)"', line)
        if not m:
            raise SystemExit(f"README.md: a package download names no -o \"$workdir/...\": {line.strip()}")
        block = script.swap(block, line, f'cp ~/cand/"{m.group(1)}" "$workdir/"\n', "pre-tag: candidate")
    return block


def readme_swap(script: Script, block: str, release: str) -> str:
    """Apply the block's "# Ubuntu X.Y: this line instead" comment on release X.Y."""
    lines = block.splitlines(keepends=True)
    for i, line in enumerate(lines):
        m = INSTEAD.match(line.rstrip("\n"))
        if not m or release != f"Ubuntu {m.group(1)}":
            continue
        active = [j for j in range(i) if lines[j].startswith("sudo add-apt-repository ")]
        if not active or i + 1 >= len(lines) or not lines[i + 1].startswith("# sudo "):
            raise SystemExit(f"README.md: the {release} swap has no line above it or none commented below")
        why = f"{release}: README says use this line instead"
        block = script.swap(block, lines[active[-1]], f"# {lines[active[-1]]}", why)
        block = script.swap(block, lines[i + 1], lines[i + 1][2:], why)
    return block


def install_probe(vm: str) -> str:
    """A harness line that fails unless the package is installed."""
    return "rpm -q buoy-wm" if vm.startswith("f") else "dpkg-query -W buoy-wm"


def package(script: Script, readme: Readme, vm: str, substitute: bool) -> None:
    """The README's install block for this VM's family, the PPA block first on Ubuntu."""
    if vm.startswith("f"):
        (rpm,) = readme.blocks(FEDORA, "sh", 1)
        script.add(f"# ---- README: {FEDORA} ----", pre_tag(script, rpm) if substitute else rpm)
    else:
        ppa, deb = readme.blocks(UBUNTU, "sh", 2)
        script.add("# ---- README: Ubuntu PPA block ----", readme_swap(script, ppa, lookup(vm).release),
                   "# ---- README: Ubuntu .deb block ----", pre_tag(script, deb) if substitute else deb)
    script.add("# HARNESS", install_probe(vm))


def multiplexer(script: Script, readme: Readme, vm: str) -> None:
    """The README route to a multiplexer this VM proves (vms.py)."""
    route = lookup(vm).multiplexer
    if route == "asset":
        (block,) = readme.blocks(MULTIPLEXER, "sh", 1)
        script.add("# ---- README (Requirements): the zellij asset into /usr/local/bin ----", block,
                   "# HARNESS", "zellij --version")
    elif route == "cargo":
        script.add("# ---- PROSE (Requirements): cargo install zellij, then copy it into /usr/local/bin ----",
                   readme.code_span(MULTIPLEXER, r"sudo dnf install cargo perl-core"),
                   readme.code_span(MULTIPLEXER, r"cargo install --locked zellij"),
                   readme.code_span(MULTIPLEXER, r"sudo install ~/\.cargo/bin/zellij /usr/local/bin/"),
                   "# HARNESS", "zellij --version")
    elif route == "tmux":
        (toml,) = readme.blocks(MULTIPLEXER, "toml", 1)
        script.add("# ---- PROSE (Requirements, Ubuntu install): the tmux [defaults] block, then chmod 600 ----",
                   "# HARNESS", "mkdir -p ~/.config/buoy", script.heredoc("~/.config/buoy/config.toml", toml),
                   "# ---- PROSE (When something in the file is wrong) ----",
                   readme.code_span(TRUST, r"chmod 600 ~/\.config/buoy/config\.toml"),
                   "# HARNESS", "stat -c '%a %n' ~/.config/buoy/config.toml")
    else:
        raise SystemExit(f"{vm}: unknown multiplexer route {route!r}")


def status_bar(script: Script, readme: Readme) -> None:
    """The Status bar config file (its first line names the path), then First login's enable."""
    (jsonc,) = readme.blocks(STATUS_BAR, "jsonc", 1)
    path = re.match(r"// (\S+)\n", jsonc)
    if not path:
        raise SystemExit("README.md: the Status bar block's first line does not name its file")
    script.add("# ---- PROSE (Status bar): the waybar config file ----",
               "# HARNESS", f"mkdir -p {path.group(1).rsplit('/', 1)[0]}",
               script.heredoc(path.group(1), jsonc),
               "# ---- PROSE (Running it): enable waybar ----",
               readme.code_span(PACKAGED_SESSION, r"systemctl --user enable\s+waybar\.service"),
               "# HARNESS", "systemctl --user is-enabled waybar.service")


def main(readme_path: str, vm: str, out: str, substitute: bool) -> None:
    """Write the VM's script to out and print the substitution log."""
    lookup(vm)
    readme = Readme(pathlib.Path(readme_path).read_text())
    script = Script(vm)
    package(script, readme, vm, substitute)
    multiplexer(script, readme, vm)
    status_bar(script, readme)
    pathlib.Path(out).write_text("\n".join(p.rstrip("\n") for p in script.parts) + "\n")
    print("\n".join(script.log) or "# no substitutions")


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a != "--no-substitute"]
    if len(args) != 3:
        raise SystemExit(__doc__)
    main(*args, substitute="--no-substitute" not in sys.argv)
